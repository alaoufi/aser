/** رابط صفحة الأكلة. الاسم العربي يُرمَّز في الرابط. */
export const dishPath = (d: Pick<Dish, "slug">) =>
  `/akalat/${encodeURIComponent(d.slug)}`;

/** الأكلة من جزء الرابط (يصل مرمَّزًا أو لا) أو من كلمة بحث مطابقة لاسمها. */
export function findDish(value: string) {
  let slug = value.trim();
  try {
    slug = decodeURIComponent(slug);
  } catch {
    // ترميز ناقص: يُقارن كما هو.
  }
  return DISHES.find((d) => d.slug === slug || d.search === slug) ?? null;
}
