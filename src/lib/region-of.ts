/** المنطقة الإدارية الأقرب للنقطة، أو null خارج المملكة. */
export function regionOf(point: LatLng): string | null {
  if (!inSaudiBounds(point)) return null;
  const [lat, lng] = point;
  const k = Math.cos((lat * Math.PI) / 180);
  let best: string | null = null;
  let min = Infinity;
  for (const [region, a, b] of anchors) {
    const d = (lat - a) ** 2 + ((lng - b) * k) ** 2;
    if (d < min) {
      min = d;
      best = region;
    }
  }
  return best;
}
